"""Cross-source football prediction consensus scan.

Reads the current fixture list generated by the existing scanner, checks the
five free public prediction sites, and writes a transparent consensus report.
A source is counted only when a match and explicit selection are both found.
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from app.external_prediction_sources import SOURCES, analyze_match

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "reports" / "latest_auto_analysis.json"
OUTPUT = ROOT / "reports" / "common_prediction_matches.json"


def main() -> int:
    if not INPUT.exists():
        print(f"Missing fixture report: {INPUT}")
        return 2
    data = json.loads(INPUT.read_text(encoding="utf-8"))
    fixtures = data.get("all_scanned") or data.get("top_matches") or []
    results = []
    for item in fixtures:
        home, away = item.get("home"), item.get("away")
        if not home or not away:
            continue
        evidence = analyze_match(home, away, reset_cache=(len(results) == 0))
        source_rows = evidence.get("sources", [])
        explicit = [r for r in source_rows if r.get("tip")]
        found = [r for r in source_rows if r.get("match_found")]
        consensus = evidence.get("consensus", [])
        results.append({
            "home": home, "away": away,
            "fixture_date": item.get("fixture_date"),
            "sources_checked": len(source_rows),
            "sources_with_match": len(found),
            "sources_with_explicit_tip": len(explicit),
            "consensus": consensus,
            "source_evidence": source_rows,
            "common_match": len(found) >= 2,
            "multi_source_tip": len(explicit) >= 2,
        })
    results.sort(key=lambda x: (x["multi_source_tip"], x["sources_with_explicit_tip"],
                                x["sources_with_match"]), reverse=True)
    report = {
        "generated_at": datetime.now().astimezone().isoformat(),
        "source_names": [{"key": s.key, "name": s.name, "url": s.url} for s in SOURCES],
        "fixture_count": len(results),
        "common_match_count": sum(r["common_match"] for r in results),
        "multi_source_tip_count": sum(r["multi_source_tip"] for r in results),
        "matches": results,
        "note": "A common fixture means at least two sites mention both teams; a consensus tip requires at least two explicit parsed tips. Missing/blocked pages are not negative votes.",
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Fixtures checked: {len(results)}")
    print(f"Common fixtures (>=2 sources): {report['common_match_count']}")
    print(f"Multi-source explicit tips (>=2): {report['multi_source_tip_count']}")
    for row in results[:15]:
        print(f"- {row['home']} vs {row['away']}: pages={row['sources_with_match']}/5, "
              f"explicit_tips={row['sources_with_explicit_tip']}/5, consensus={row['consensus']}")
    print(f"Report: {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
